#!/bin/bash

# Скрипт создания самоподписанных SSL сертификатов для OPTISPORT
# Используется для временного HTTPS доступа к серверу по IP адресу
# ВАЖНО: Этот скрипт необходимо запускать из корневой директории проекта!

echo "🔐 Создание самоподписанных SSL сертификатов для OPTISPORT..."

# Определяем директорию для сертификатов относительно корня проекта
CERT_DIR="docker/nginx/ssl"

# Создаем директорию, если она не существует
mkdir -p "$CERT_DIR"

# Пути к файлам
KEY_PATH="$CERT_DIR/key.pem"
CERT_PATH="$CERT_DIR/cert.pem"

# Проверяем, существуют ли уже сертификаты
if [ -f "$CERT_PATH" ] && [ -f "$KEY_PATH" ]; then
    echo "✅ Сертификаты уже существуют в $CERT_DIR. Пропускаем создание."
else
    # Создаем приватный ключ
    openssl genrsa -out "$KEY_PATH" 2048

    # Создаем самоподписанный сертификат
    openssl req -new -x509 -key "$KEY_PATH" -out "$CERT_PATH" -days 365 -subj "/C=RU/ST=Moscow/L=Moscow/O=FREESPORT/OU=IT/CN=5.35.124.149"

    echo "✅ Сертификаты успешно созданы в директории $CERT_DIR:"
    echo "   - $KEY_PATH (приватный ключ)"
    echo "   - $CERT_PATH (сертификат)"
fi

echo ""
echo "📋 Инструкции по использованию:"
echo "1. Убедитесь, что вы обновили код на сервере (включая этот скрипт и docker-compose.yml)."
echo "2. Перезапустите контейнеры из корневой директории проекта:"
echo "   docker-compose down && docker-compose up -d"

echo ""
echo "⚠️  ВАЖНО:"
echo "- Эти сертификаты самоподписанные, и браузеры будут показывать предупреждение о безопасности."
echo "- Для доступа к сайту https://5.35.124.149 вам нужно будет принять риски и добавить исключение безопасности в браузере."
echo "- Для реальной эксплуатации (production) используйте сертификаты от Let's Encrypt или другого доверенного центра."