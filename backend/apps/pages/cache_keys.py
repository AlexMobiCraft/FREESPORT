"""
Ключи кэша приложения pages.

Вынесены отдельным модулем, потому что используются и во view (запись), и в
сигнале инвалидации (удаление): разъезд имён ключей между этими двумя местами
означает вечно протухший кэш, который никто не сбрасывает.
"""

# Полный сериализованный список опубликованных страниц.
# ВАЖНО: имя ключа отличается от исторического `pages_list` намеренно — под
# старым именем лежал готовый пагинированный ответ (dict), а не список, и после
# выката нового кода такое значение сломало бы пагинацию. Старые записи просто
# истекут по своему TTL.
PAGES_LIST_CACHE_KEY = "pages_list_serialized"

# Время жизни кэша списка: сутки. Публикация страницы сбрасывает его сигналом
# немедленно, поэтому длинный TTL задержку видимости не создаёт.
PAGES_LIST_CACHE_TTL = 60 * 60 * 24
